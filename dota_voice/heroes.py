# raw npc name -> human-readable name, for a string hero id
HERO_NAMES: dict[str, str] = {name: loc for name, loc in HEROES.values()}


def hero_display(raw: str | None) -> str:
    """Turn a raw GSI hero id into a readable name (``npc_dota_hero_lion`` -> ``Lion``).

    Accepts a string id, a bare key (``lion``) or a numeric id as text.
    """
    if not raw:
        return ""
    key = str(raw).strip()
    if key in HERO_NAMES:
        return HERO_NAMES[key]
    if key.isdigit():
        entry = HEROES.get(int(key))
        return entry[1] if entry else ""
    for prefix in ("npc_dota_hero_", "npc_dota_"):
        if key.startswith(prefix):
            key = key[len(prefix):]
            break
    entry = HEROES_BY_KEY.get(key)
    if entry:
        return entry[1]
    return key.replace("_", " ").title()


def hero_npc(raw: str | None) -> str:
    """Canonical ``npc_dota_hero_<key>`` id for a hero, or "" if unknown.

    GSI may send the hero as a string name, a bare key or a numeric id; the icon
    URL and the "was a hero picked?" check both need the canonical string form.
    """
    if raw is None:
        return ""
    key = str(raw).strip()
    if key.startswith("npc_dota_hero_"):
        return key if key in HERO_NAMES else ""
    if key.isdigit():
        entry = HEROES.get(int(key))
        return entry[0] if entry else ""
    entry = HEROES_BY_KEY.get(key)
    return entry[0] if entry else ""


