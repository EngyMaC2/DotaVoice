"""Player and account safety policy.

This module turns the project's safety promises into something the code can
actually enforce and report on, instead of leaving them as prose in a README.

The promises
------------
**VAC safety.** The app only uses mechanisms Valve publishes for outside tools:

* it reads Game State Integration - an official, opt-in HTTP feed;
* it never reads Dota 2's memory, never injects a DLL or hooks a function inside
  the game, and never automates gameplay input;
* any overlay is an *external* window or a browser source, never an in-process
  hook. Internal overlays are the classic way to get flagged, so the policy
  treats one as a hard error.

**Account safety.** The app never asks for Steam credentials:

* it never collects a Steam login or password;
* it never stores, transmits or logs one;
* the optional Steam SDR transport uses the already-running Steam client, and is
  off unless an operator turns it on knowingly.

**Local control.** Mute is local. Muting a player stops sending to them and
playing them; it does not remove them for anyone else, and it needs no server.

The functions here are used in two places: as guards inside the app (for example
before enabling SDR) and to produce a Russian-language report shown in the UI.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Iterable

__all__ = [
    "Invariant",
    "PolicyViolation",
    "SafetyPolicy",
    "SafetyReport",
    "audit_config",
    "default_policy",
    "looks_like_credential_field",
    "report_text",
]


class Invariant(str, Enum):
    """The invariants the app must not break."""

    NO_MEMORY_READ = "no_memory_read"
    NO_PROCESS_INJECTION = "no_process_injection"
    NO_GAMEPLAY_AUTOMATION = "no_gameplay_automation"
    NO_CREDENTIAL_REQUEST = "no_credential_request"
    NO_CREDENTIAL_STORAGE = "no_credential_storage"
    EXTERNAL_OVERLAY = "external_overlay"
    LOCAL_MUTE = "local_mute"


_INVARIANT_TEXT: dict[Invariant, str] = {
    Invariant.NO_MEMORY_READ: (
        "Приложение не читает память Dota 2. Состояние берётся только из "
        "официального интерфейса Game State Integration."
    ),
    Invariant.NO_PROCESS_INJECTION: (
        "Приложение не внедряется в процесс игры: ни DLL, ни хуков, ни "
        "перехвата функций."
    ),
    Invariant.NO_GAMEPLAY_AUTOMATION: (
        "Приложение не автоматизирует игровые действия и не управляет вводом "
        "в игре."
    ),
    Invariant.NO_CREDENTIAL_REQUEST: (
        "Приложение никогда не запрашивает логин или пароль Steam."
    ),
    Invariant.NO_CREDENTIAL_STORAGE: (
        "Приложение не хранит и не передаёт учётные данные Steam."
    ),
    Invariant.EXTERNAL_OVERLAY: (
        "Оверлей — внешнее прозрачное окно или источник для OBS, а не хук "
        "внутри игры."
    ),
    Invariant.LOCAL_MUTE: (
        "Мут локальный: он касается только вас и не влияет на других игроков."
    ),
}


class PolicyViolation(RuntimeError):
    """Raised when an action would break a safety invariant."""

    def __init__(self, invariant: Invariant, detail: str = "") -> None:
        self.invariant = invariant
        message = _INVARIANT_TEXT[invariant]
        super().__init__(f"{message}{(' — ' + detail) if detail else ''}")


# Field names that would indicate a credential is being handled.
_CREDENTIAL_PATTERNS = (
    re.compile(r"(^|_)password($|_)"),
    re.compile(r"(^|_)passwd($|_)"),
    re.compile(r"(^|_)passphrase($|_)"),
    re.compile(r"steam_?login"),
    re.compile(r"steam_?password"),
    re.compile(r"(^|_)secret($|_)"),
    re.compile(r"(^|_)credential"),
    re.compile(r"(^|_)api_?key($|_)"),
    re.compile(r"(^|_)token($|_)"),
)

# A field that is fine to keep: the GSI auth token is generated by us, is not a
# Steam credential, and never leaves the local machine.
_ALLOWED_CREDENTIAL_FIELDS = frozenset({"gsi_token", "discord_bot_token"})


def looks_like_credential_field(name: str) -> bool:
    """Whether a config key name suggests it holds a credential."""
    lowered = name.strip().lower()
    if lowered in _ALLOWED_CREDENTIAL_FIELDS:
        return False
    return any(pattern.search(lowered) for pattern in _CREDENTIAL_PATTERNS)


@dataclass
class SafetyPolicy:
    """The invariants as enforceable flags.

    The defaults are the safe ones; the only flag that can legitimately change is
    :attr:`steam_sdr_enabled`, and only with an explicit operator decision.
    """

    read_game_memory: bool = False
    inject_into_game: bool = False
    automate_gameplay: bool = False
    request_steam_credentials: bool = False
    internal_overlay: bool = False
    local_mute: bool = True
    # Steam SDR is opt-in; see dota_voice/net/transport.py for the trade-offs.
    steam_sdr_enabled: bool = False

    def guard(self) -> None:
        """Raise if any flag is set to an unsafe value."""
        if self.read_game_memory:
            raise PolicyViolation(Invariant.NO_MEMORY_READ)
        if self.inject_into_game:
            raise PolicyViolation(Invariant.NO_PROCESS_INJECTION)
        if self.automate_gameplay:
            raise PolicyViolation(Invariant.NO_GAMEPLAY_AUTOMATION)
        if self.request_steam_credentials:
            raise PolicyViolation(Invariant.NO_CREDENTIAL_REQUEST)
        if self.internal_overlay:
            raise PolicyViolation(Invariant.EXTERNAL_OVERLAY)
        if not self.local_mute:
            raise PolicyViolation(Invariant.LOCAL_MUTE)

    def guard_sdr(self) -> None:
        """Raise unless the Steam SDR transport was explicitly enabled."""
        if not self.steam_sdr_enabled:
            raise PolicyViolation(
                Invariant.NO_PROCESS_INJECTION,
                "транспорт Steam SDR не включён (DOTAVOICE_P2P_STEAM_SDR=1)",
            )

    def invariants(self) -> dict[str, str]:
        return {invariant.value: _INVARIANT_TEXT[invariant] for invariant in Invariant}

    def as_dict(self) -> dict[str, Any]:
        return {
            "read_game_memory": self.read_game_memory,
            "inject_into_game": self.inject_into_game,
            "automate_gameplay": self.automate_gameplay,
            "request_steam_credentials": self.request_steam_credentials,
            "internal_overlay": self.internal_overlay,
            "local_mute": self.local_mute,
            "steam_sdr_enabled": self.steam_sdr_enabled,
        }


def default_policy() -> SafetyPolicy:
    return SafetyPolicy()


@dataclass
class SafetyReport:
    """Result of auditing a configuration against the policy."""

    ok: bool = True
    violations: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    invariants: dict[str, str] = field(default_factory=dict)

    def as_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "violations": list(self.violations),
            "notes": list(self.notes),
            "invariants": dict(self.invariants),
        }


def audit_config(config: Any, policy: SafetyPolicy | None = None) -> SafetyReport:
    """Check an :class:`~dota_voice.appconfig.AppConfig`-like object.

    Looks for two things: unsafe policy flags, and any field that appears to hold
    a credential. ``config`` may be a dataclass, an object with ``__dict__``, or a
    plain mapping (as arrives over HTTP), so this stays testable without the
    desktop layer.
    """
    policy = policy or default_policy()
    report = SafetyReport(invariants=policy.invariants())

    try:
        policy.guard()
    except PolicyViolation as exc:
        report.ok = False
        report.violations.append(str(exc))

    if isinstance(config, dict):
        values = config
    else:
        values = getattr(config, "__dict__", {}) or {}
    for name, value in values.items():
        if not isinstance(value, str):
            continue
        if looks_like_credential_field(name) and value:
            report.ok = False
            report.violations.append(
                f"Поле «{name}» похоже на учётные данные. Приложение не должно "
                "хранить логины, пароли и секреты Steam."
            )

    if policy.steam_sdr_enabled:
        report.notes.append(
            "Транспорт Steam SDR включён осознанно. Это значит, что приложение "
            "использует Steamworks: возможны ограничения со стороны Valve, "
            "вплоть до блокировки аккаунта. Оценивайте риск сами."
        )
    return report


def report_text(report: SafetyReport) -> str:
    """Human-readable Russian summary for the UI."""
    lines: list[str] = []
    lines.append("Проверка безопасности: " + ("всё в порядке" if report.ok else "есть замечания"))
    if report.violations:
        lines.append("")
        lines.append("Нарушения:")
        lines.extend(f"• {item}" for item in report.violations)
    lines.append("")
    lines.append("Гарантии:")
    lines.extend(f"• {text}" for text in report.invariants.values())
    if report.notes:
        lines.append("")
        lines.append("Примечания:")
        lines.extend(f"• {note}" for note in report.notes)
    return "\n".join(lines)


def forbidden_modules(modules: Iterable[str]) -> list[str]:
    """Return any loaded module names that would imply memory access or injection.

    Used as a defensive audit: if one of these ever shows up in ``sys.modules``
    the app has drifted away from the policy and should say so loudly.
    """
    risky = ("pymem", "frida", "pyinject", "readprocessmemory", "ctypes.windll.kernel32")
    lowered = [m.lower() for m in modules]
    return [m for m in lowered if any(token in m for token in risky)]
